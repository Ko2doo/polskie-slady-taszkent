/**
 * CustomPointsBuilder
 *
 * Purpose:
 *   Encapsulates logic for rendering user-created points (markers) on a MapLibre map.
 *   Unlike MapPointsBuilder, the data is not known in advance: points are added
 *   one by one at runtime, after the user fills in the form in the map editor dialog.
 *   It:
 *     - Loads and registers marker icons on the map
 *     - Adds one GeoJSON source and the symbol layers (icons, title labels) from `markers.mapLayer`
 *     - Keeps rendered points in memory (needed to restore them after a style change)
 *     - Updates the source each time a point is added, updated, removed or cleared
 *     - Shows or hides all custom points (the markers filter), the state survives a theme change
 *     - Shows a popup (title + optional preview) on marker click and hands the point id
 *       over to popupTrigger when the user presses "Read more"
 *
 * Requirements:
 *   - `currentMap` must be an initialized MapLibre map instance
 *   - `markers.icons` is an array of objects { name, url }, one of them must be
 *     the default icon (see `markers.defaultIconName`)
 *   - `markers.mapLayer` is an array of MapLibre layer definitions (the same structure as in MARKER_CONFIG),
 *     the ids of these layers are also used for click handling
 *   - A point passed to addPoint() is an object:
 *       - `id`       - required, unique id (generated by the custom points state, later by the DB)
 *       - `coords`   - { lng, lat } in WGS84 (the same shape that the map editor controller stores)
 *       - `title`    - required, non-empty string
 *       - `preview`  - optional, image URL shown in the popup
 *       - `iconName` - optional, name of a registered icon (falls back to the default icon)
 *   - The article text is NOT stored here. The popup only passes the point `id` to `popupTrigger`,
 *     the full text is resolved by the article popup from the custom points state.
 *   - `i18n` provides translation functions:
 *       - `i18n.popupLink()` -> string shown as popup link text
 *
 * Typical usage (inside a Map.svelte component):
 *
 *   const builder = CustomPointsBuilder.create()
 *     .withMap(map)
 *     .withStyleVersion(styleVersion)
 *     .withI18n({ popupLink: () => i18n.t('ui:buttons:readMore') })
 *     .withPopup((id) => articlePopupState.open(id))
 *     .withPopupGuard(() => !userCustomPointsToggler.value)
 *     .withMarkers(CUSTOM_POINTS_CONFIG)
 *     .build();
 *
 *   // Once, after map "load" (and again after every style change):
 *   builder.init();
 *
 *   // Later, when the user presses "Save" in the editor dialog:
 *   builder.addPoint({ id, coords: { lng, lat }, title, preview });
 *
 *   // Markers filter: hide / show all custom points
 *   builder.setVisible(false);
 *
 *   // Map editor mode: which custom point was tapped, updating and removing it
 *   const pointId = builder.getPointIdAt(e.point);
 *   builder.updatePoint({ id, title });
 *   builder.removePoint(id);
 *
 * Note:
 *   Changing the map style (theme switch) removes all images, sources and layers.
 *   After the new style is loaded call setStyleVersion() and init() again,
 *   already created points will be restored from memory.
 *
 * @class CustomPointsBuilder
 */

import * as maplibreGL from 'maplibre-gl';
import { createLogger, IS_DEBUG } from '@/utils/debugMode';
import { getLayerVisibility, setLayersVisibility } from '@/utils/mapLayerVisibility';
import { createPopupHTML } from './mapPopupHtml';

const customPointsLogger = createLogger('CustomPointsBuilder');

export class CustomPointsBuilder {
  /**
   * Private constructor - use CustomPointsBuilder.create() instead
   * @private
   */
  constructor() {
    // Configuration state
    this._config = {
      currentMap: null,
      styleVersion: 0,
      i18n: {
        popupLink: null,
      },
      popupTrigger: () => {},
      isPopupEnabled: () => true,
      markers: {
        sourceName: 'custom-points-source',
        defaultIconName: 'default',
        icons: [],
        mapLayer: [],
      },
    };

    // Internal state
    this._points = [];
    this._onMarkerClick = null;
    this._clickLayerIds = [];
    this._iconImages = [];
    this._isVisible = true;
    this._isBuilt = false;
    this._isReady = false;
  }

  // ========================================
  // BUILDER PATTERN METHODS
  // ========================================

  /**
   * Create a new builder instance
   * @returns {CustomPointsBuilder}
   */
  static create() {
    return new CustomPointsBuilder();
  }

  /**
   * Set the MapLibre map instance
   * @param {maplibreGL.Map} map - Initialized MapLibre map
   * @returns {CustomPointsBuilder}
   */
  withMap(map) {
    this._config.currentMap = map;
    return this;
  }

  /**
   * Set the style version (for theme changes)
   * @param {number} version - Current style version
   * @returns {CustomPointsBuilder}
   */
  withStyleVersion(version) {
    this._config.styleVersion = version;
    return this;
  }

  /**
   * Set the i18n translation functions
   * @param {Object} i18n - Object with translation functions
   * @param {Function} i18n.popupLink - Function to get popup link text
   * @returns {CustomPointsBuilder}
   */
  withI18n(i18n) {
    if (i18n && typeof i18n === 'object') {
      this._config.i18n = { ...this._config.i18n, ...i18n };
    }
    return this;
  }

  /**
   * Set the popup function for Popup state
   * @param {Function} popupTrigger - Function called with point ID on "Read more" click
   * @returns {CustomPointsBuilder}
   */
  withPopup(popupTrigger) {
    if (typeof popupTrigger === 'function') {
      this._config.popupTrigger = popupTrigger;
    }
    return this;
  }

  /**
   * Set the function that decides whether a marker click should open a popup
   * (for example, popups must be disabled while the map editor mode is active)
   * @param {Function} isPopupEnabled - Function returning true if the popup may be shown
   * @returns {CustomPointsBuilder}
   */
  withPopupGuard(isPopupEnabled) {
    if (typeof isPopupEnabled === 'function') {
      this._config.isPopupEnabled = isPopupEnabled;
    }
    return this;
  }

  /**
   * Configure markers
   * @param {Object} config - Marker configuration
   * @param {string} [config.sourceName] - GeoJSON source name
   * @param {string} [config.defaultIconName] - Icon used when a point has no (or unknown) iconName
   * @param {Array} [config.icons] - Array of { name, url } objects
   * @param {Array} [config.mapLayer] - Array of MapLibre layer definitions (icons, labels)
   * @returns {CustomPointsBuilder}
   */
  withMarkers(config) {
    if (config && typeof config === 'object') {
      this._config.markers = { ...this._config.markers, ...config };
    }
    return this;
  }

  /**
   * Finalize and validate configuration
   * @returns {CustomPointsBuilder}
   * @throws {Error} If required configuration is missing
   */
  build() {
    if (!this._config.currentMap) {
      throw new Error('[CustomPointsBuilder] Map instance is required. Use withMap() method.');
    }

    const { icons, defaultIconName, mapLayer } = this._config.markers;

    if (!Array.isArray(mapLayer) || mapLayer.length === 0) {
      throw new Error('[CustomPointsBuilder] At least one layer is required. Use withMarkers({ mapLayer }).');
    }

    if (!Array.isArray(icons) || icons.length === 0) {
      throw new Error('[CustomPointsBuilder] At least one icon is required. Use withMarkers({ icons }).');
    }

    const hasDefaultIcon = icons.some((icon) => icon.name === defaultIconName);

    if (!hasDefaultIcon) {
      throw new Error(`[CustomPointsBuilder] Default icon "${defaultIconName}" is not in the icons list.`);
    }

    this._isBuilt = true;
    return this;
  }

  // ========================================
  // PUBLIC API METHODS
  // ========================================

  /**
   * Update style version (called on theme changes)
   * @param {number} version - New style version
   */
  setStyleVersion(version) {
    this._config.styleVersion = version;
  }

  /**
   * Register icons, add the source and the layers for custom points to the map
   * and attach the click handler for popups.
   * Safe to call several times: already existing images, sources and layers are skipped.
   * @returns {Promise<void>}
   */
  async init() {
    const map = this._config.currentMap;
    if (!map) {
      IS_DEBUG && customPointsLogger.warn('Cannot init: map not available');
      return;
    }

    if (!this._isBuilt) {
      IS_DEBUG && customPointsLogger.warn('Cannot init: call build() first');
      return;
    }

    const myVersion = this._config.styleVersion;
    const { icons, sourceName, mapLayer } = this._config.markers;

    // Release images from the previous init() (for example, after a theme change)
    this._releaseImages();

    // Load icon images
    let loadedIcons = [];

    try {
      const iconPromises = icons.map((icon) => this._loadIcon(icon));
      loadedIcons = await Promise.all(iconPromises);
    } catch (error) {
      IS_DEBUG && customPointsLogger.error('Failed to load icons:', error);
      return;
    }

    // Check if style version changed (theme switched during loading)
    if (this._config.styleVersion !== myVersion) {
      IS_DEBUG && customPointsLogger.log('Style version changed, aborting init');
      return;
    }

    // Register icon images
    loadedIcons.forEach(({ name, image }) => {
      const imageId = this._getImageId(name);

      if (map.hasImage(imageId)) {
        IS_DEBUG && customPointsLogger.log(`Icon "${imageId}" already registered, skipping`);
        return;
      }

      map.addImage(imageId, image);
      IS_DEBUG && customPointsLogger.log(`Icon "${imageId}" registered`);
    });

    // Add source
    if (map.getSource(sourceName)) {
      IS_DEBUG && customPointsLogger.log(`Source "${sourceName}" already exists, skipping`);
    } else {
      map.addSource(sourceName, {
        type: 'geojson',
        data: this._buildFeatureCollection(),
      });
    }

    // Add layers
    mapLayer.forEach((layer) => {
      if (map.getLayer(layer.id)) {
        IS_DEBUG && customPointsLogger.log(`Layer "${layer.id}" already exists, skipping`);
        return;
      }

      map.addLayer({
        ...layer,
        layout: { ...layer.layout, visibility: getLayerVisibility(this._isVisible) },
      });
      IS_DEBUG && customPointsLogger.log(`Layer "${layer.id}" added`);
    });

    // Attach click handler for popups (icon layer and labels layer)
    const clickLayerIds = mapLayer.map((layer) => layer.id);
    this._attachClickHandler(clickLayerIds);

    this._isReady = true;

    IS_DEBUG && customPointsLogger.log('Custom points layer ready');
  }

  /**
   * Add a new custom point and show it on the map
   * @param {Object} point - Point data
   * @param {string} point.id - Unique point id
   * @param {Object} point.coords - { lng, lat }
   * @param {string} point.title - Required title
   * @param {string} [point.preview] - Optional preview image URL
   * @param {string} [point.iconName] - Optional icon name
   * @returns {Object|null} - Rendered point or null if the data is invalid
   */
  addPoint(point) {
    if (!this._isBuilt) {
      IS_DEBUG && customPointsLogger.warn('Cannot add point: call build() first');
      return null;
    }

    if (!point || typeof point !== 'object') {
      IS_DEBUG && customPointsLogger.error('Invalid point: object expected');
      return null;
    }

    if (!point.id) {
      IS_DEBUG && customPointsLogger.warn('Point id is required');
      return null;
    }

    const isDuplicate = this._points.some((existingPoint) => existingPoint.id === point.id);
    if (isDuplicate) {
      IS_DEBUG && customPointsLogger.warn(`Point "${point.id}" already exists, skipping`);
      return null;
    }

    const coordinates = this._transformCoords(point.coords);
    if (!coordinates) {
      IS_DEBUG && customPointsLogger.warn(`Failed to transform coords for point "${point.id}"`);
      return null;
    }

    const title = typeof point.title === 'string' ? point.title.trim() : '';
    if (!title) {
      IS_DEBUG && customPointsLogger.warn(`Point "${point.id}" has no title`);
      return null;
    }

    const preview = typeof point.preview === 'string' ? point.preview : '';

    const newPoint = {
      id: point.id,
      coordinates,
      title,
      preview,
      iconName: this._resolveIconName(point.iconName),
    };

    this._points.push(newPoint);
    this._syncSource();

    IS_DEBUG && customPointsLogger.log(`Point "${newPoint.id}" added`);

    return { ...newPoint };
  }

  /**
   * Update title and/or preview of an already rendered point.
   * The id, coordinates and icon are not changed.
   * @param {Object} point - Point data
   * @param {string} point.id - Id of the point to update
   * @param {string} point.title - Required new title
   * @param {string} [point.preview] - Optional new preview image URL
   * @returns {Object|null} - Updated point or null if the point was not found or the data is invalid
   */
  updatePoint(point) {
    if (!this._isBuilt) {
      IS_DEBUG && customPointsLogger.warn('Cannot update point: call build() first');
      return null;
    }

    if (!point || !point.id) {
      IS_DEBUG && customPointsLogger.warn('Point id is required');
      return null;
    }

    const existingPoint = this._points.find((item) => item.id === point.id);
    if (!existingPoint) {
      IS_DEBUG && customPointsLogger.warn(`Point "${point.id}" not found`);
      return null;
    }

    const title = typeof point.title === 'string' ? point.title.trim() : '';
    if (!title) {
      IS_DEBUG && customPointsLogger.warn(`Point "${point.id}" has no title`);
      return null;
    }

    existingPoint.title = title;

    if (typeof point.preview === 'string') {
      existingPoint.preview = point.preview;
    }

    this._syncSource();

    IS_DEBUG && customPointsLogger.log(`Point "${existingPoint.id}" updated`);

    return { ...existingPoint };
  }

  /**
   * Remove a single point from memory and from the map
   * @param {string} id - Id of the point to remove
   * @returns {boolean} - true if the point was removed, false if it was not found
   */
  removePoint(id) {
    if (!this._isBuilt) {
      IS_DEBUG && customPointsLogger.warn('Cannot remove point: call build() first');
      return false;
    }

    const index = this._points.findIndex((point) => point.id === id);
    if (index === -1) {
      IS_DEBUG && customPointsLogger.warn(`Point "${id}" not found`);
      return false;
    }

    this._points.splice(index, 1);
    this._syncSource();

    IS_DEBUG && customPointsLogger.log(`Point "${id}" removed`);

    return true;
  }

  /**
   * Find the custom point rendered under a screen position (icon or title label)
   * @param {Object} screenPoint - { x, y } position in pixels, e.g. `e.point` of a MapLibre event
   * @returns {string|null} - Point id or null if there is no custom point at this position
   */
  getPointIdAt(screenPoint) {
    const map = this._config.currentMap;
    if (!map || !this._isReady) return null;

    // Querying a layer that is not in the style (e.g. during a theme change) would fire an error event
    const layerIds = this._clickLayerIds.filter((layerId) => map.getLayer(layerId));
    if (layerIds.length === 0) return null;

    const features = map.queryRenderedFeatures(screenPoint, { layers: layerIds });
    if (features.length === 0) return null;

    return features[0].properties.id;
  }

  /**
   * Show or hide all custom points (icons and labels).
   * The value is kept and applied to the layers that are (re)added later, e.g. after a theme change.
   * @param {boolean} isVisible - true to show, false to hide
   */
  setVisible(isVisible) {
    this._isVisible = isVisible;

    const map = this._config.currentMap;
    if (!map) return;

    const layerIds = this._config.markers.mapLayer.map((layer) => layer.id);
    setLayersVisibility(map, layerIds, isVisible);

    IS_DEBUG && customPointsLogger.log(`Visibility set to ${isVisible}`);
  }

  /**
   * Get all rendered points
   * @returns {Array} - Copy of points array
   */
  getPoints() {
    return this._points.map((point) => ({ ...point }));
  }

  /**
   * Remove all points from memory and from the map
   */
  clearPoints() {
    this._points = [];
    this._syncSource();

    IS_DEBUG && customPointsLogger.log('Points cleared');
  }

  /**
   * Clean up all resources and event listeners
   */
  dispose() {
    // Remove click listener
    this._detachClickHandler();

    // Clean up image references to prevent memory leaks
    this._releaseImages();
    this._isReady = false;

    IS_DEBUG && customPointsLogger.log('Disposed');
  }

  // ========================================
  // PRIVATE HELPER METHODS
  // ========================================

  /**
   * Load a single icon image
   * @private
   * @param {Object} icon - { name, url }
   * @returns {Promise<Object>} - Resolves with { name, image }
   */
  _loadIcon(icon) {
    return new Promise((resolve, reject) => {
      if (!icon || !icon.name || !icon.url) {
        reject(new Error('Icon requires "name" and "url"'));
        return;
      }

      const image = new Image();
      image.crossOrigin = 'anonymous';

      image.onload = () => {
        resolve({ name: icon.name, image });
      };

      image.onerror = () => {
        reject(new Error(`Failed to load icon "${icon.name}" from "${icon.url}"`));
      };

      this._iconImages.push(image);
      image.src = icon.url;
    });
  }

  /**
   * Release loaded icon images (MapLibre keeps its own copy after addImage)
   * @private
   */
  _releaseImages() {
    this._iconImages.forEach((image) => {
      image.onload = null;
      image.onerror = null;
      image.src = '';
    });

    this._iconImages = [];
  }

  /**
   * Build the id under which the icon is registered on the map
   * @private
   * @param {string} iconName - Icon name
   * @returns {string}
   */
  _getImageId(iconName) {
    return `${iconName}-custom-point`;
  }

  /**
   * Return iconName if it is registered, otherwise the default icon name
   * @private
   * @param {string} iconName - Requested icon name
   * @returns {string}
   */
  _resolveIconName(iconName) {
    const icons = this._config.markers.icons;
    const exists = icons.some((icon) => icon.name === iconName);

    if (exists) {
      return iconName;
    }

    return this._config.markers.defaultIconName;
  }

  /**
   * Transform coordinates from { lng, lat } to [lon, lat] for GeoJSON
   * @private
   * @param {Object} coords - { lng, lat } object
   * @returns {Array|null} - [lon, lat] array or null if invalid
   */
  _transformCoords(coords) {
    if (!coords || typeof coords !== 'object') {
      return null;
    }

    const { lng, lat } = coords;

    if (typeof lng !== 'number' || typeof lat !== 'number' || Number.isNaN(lng) || Number.isNaN(lat)) {
      return null;
    }

    return [lng, lat];
  }

  /**
   * Build GeoJSON FeatureCollection from rendered points
   * @private
   * @returns {Object} - GeoJSON FeatureCollection
   */
  _buildFeatureCollection() {
    const features = this._points.map((point) => ({
      type: 'Feature',
      geometry: {
        type: 'Point',
        coordinates: point.coordinates,
      },
      properties: {
        id: point.id,
        title: point.title,
        preview: point.preview, // Popup location preview
        icon: this._getImageId(point.iconName),
      },
    }));

    return {
      type: 'FeatureCollection',
      features,
    };
  }

  /**
   * Push current points to the map source.
   * If the source does not exist yet, nothing happens: init() will pick up the points from memory.
   * @private
   */
  _syncSource() {
    const map = this._config.currentMap;
    if (!map) return;

    const source = map.getSource(this._config.markers.sourceName);
    if (!source) return;

    source.setData(this._buildFeatureCollection());
  }

  /**
   * Attach click handler to the given layers (icons and labels)
   * @private
   * @param {Array<string>} layerIds - Ids of the layers that open the popup on click
   */
  _attachClickHandler(layerIds) {
    const map = this._config.currentMap;
    if (!map) return;

    // Clean up previous listener, otherwise repeated init() would stack handlers
    this._detachClickHandler();

    this._onMarkerClick = (e) => this._handleMarkerClick(e);
    this._clickLayerIds = layerIds;

    layerIds.forEach((layerId) => {
      map.on('click', layerId, this._onMarkerClick);
    });

    IS_DEBUG && customPointsLogger.log('Click handler attached to layers:', layerIds);
  }

  /**
   * Detach click handler from the custom points layers
   * @private
   */
  _detachClickHandler() {
    const map = this._config.currentMap;
    if (!map) return;

    if (this._onMarkerClick && this._clickLayerIds.length > 0) {
      this._clickLayerIds.forEach((layerId) => {
        map.off('click', layerId, this._onMarkerClick);
      });
    }

    this._onMarkerClick = null;
    this._clickLayerIds = [];
  }

  /**
   * Create popup HTML content
   * @private
   * @param {string} title - Point title
   * @param {string} id - Point ID
   * @param {string} preview - Preview image URL
   * @returns {string} - HTML string
   */
  _createPopupHTML(title, id, preview) {
    return createPopupHTML({ title, id, preview, popupLinkFn: this._config.i18n.popupLink });
  }

  /**
   * Handle marker click event
   * @private
   * @param {Object} e - MapLibre click event
   */
  _handleMarkerClick(e) {
    // Popups are disabled, for example while the map editor mode is active
    if (!this._config.isPopupEnabled()) return;

    if (!e?.features?.length) return;

    const feature = e.features[0];
    const coords = feature.geometry.coordinates;
    const { id, title, preview } = feature.properties;

    // Create popup
    const popup = new maplibreGL.Popup({
      closeButton: false,
      closeOnClick: true,
    }).setLngLat(coords);

    // Create popup container
    const container = document.createElement('div');
    container.className = 'map-popup';
    container.innerHTML = this._createPopupHTML(title, id, preview);

    const articlePopup = container.querySelector('button[data-article-id]');
    if (articlePopup) {
      articlePopup.addEventListener('click', (event) => {
        event.preventDefault();
        this._config.popupTrigger(id);
      });
    }

    // Show popup
    popup.setDOMContent(container).addTo(this._config.currentMap);
  }
}
